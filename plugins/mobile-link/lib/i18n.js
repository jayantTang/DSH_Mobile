const ALIASES = { zh: 'zh-Hans', 'zh-Hans': 'zh-Hans', 'zh-CN': 'zh-Hans', 'zh-Hant': 'zh-Hant', 'zh-TW': 'zh-Hant', 'zh-HK': 'zh-Hant', ja: 'ja', ko: 'ko', es: 'es', pt: 'pt-BR', 'pt-BR': 'pt-BR', fr: 'fr', de: 'de', en: 'en' }
let language = 'zh-Hans'
export function resolveLanguage(tag) {
  if (!tag) return null
  const value = String(tag).trim().replace('_', '-')
  if (ALIASES[value]) return ALIASES[value]
  const base = value.toLowerCase().split('-')[0]
  return ALIASES[base] ?? null
}
export function setLanguage(tag) {
  const next = resolveLanguage(tag)
  if (next) language = next
  return language
}
export function currentLanguage() { return language }
export function T(key, vars = {}) {
  const text = CATALOGS[language]?.[key] ?? CATALOGS['zh-Hans'][key] ?? key
  return text.replace(/\$\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m))
}
